template<typename DetectionT>
inline cv::Mat visualise(const cv::Mat& image,
                         const std::vector<DetectionT>& dets,
                         float alpha = 0.55f) {
    cv::Mat vis = image.clone();
    for (const auto& d : dets) {
        const cv::Scalar c = color_for_class(d.class_id);
        if (!d.mask.empty()) {
            cv::Mat colour(vis.size(), CV_32FC3, c);
            cv::Mat mask3;
            cv::cvtColor(d.mask, mask3, cv::COLOR_GRAY2BGR);
            cv::Mat norm_mask;
            mask3.convertTo(norm_mask, CV_32FC3, 1.f / 255.f);
            cv::Mat vis_f;
            vis.convertTo(vis_f, CV_32FC3);
            cv::addWeighted(vis_f, 1.0, colour.mul(norm_mask), alpha, 0.0, vis_f);
            vis_f.convertTo(vis, CV_8UC3);
        }
        std::vector<std::vector<cv::Point>> contours;
        cv::findContours(d.mask, contours, cv::RETR_EXTERNAL, cv::CHAIN_APPROX_SIMPLE);
        if (contours.empty()) continue;
        cv::Rect bbox = cv::boundingRect(contours[0]);
        for (const auto& cnt : contours) bbox |= cv::boundingRect(cnt);
        cv::rectangle(vis, bbox, c, 2);
        std::ostringstream label;
        label << d.class_name << ' ' << std::fixed << std::setprecision(2) << d.score;
        int baseline = 0;
        auto ts = cv::getTextSize(label.str(), cv::FONT_HERSHEY_SIMPLEX, 0.5, 1, &baseline);
        cv::rectangle(vis, {bbox.x, bbox.y - ts.height - 6}, {bbox.x + ts.width + 4, bbox.y}, c, -1);
        cv::putText(vis, label.str(), {bbox.x + 2, bbox.y - 4},
                    cv::FONT_HERSHEY_SIMPLEX, 0.5, {255, 255, 255}, 1);
    }
    return vis;
}

